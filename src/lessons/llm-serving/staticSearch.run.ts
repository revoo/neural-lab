/**
 * Fairness search for Widget B (BatchingRace): searches static batching over
 *   batchSize ∈ [2, 4, 6, 8, 12, 16] × maxWaitMs ∈ [0, 25, 50, 100, 200, 400]
 * on `RACE_TRACE` (RTX 4090, Llama-3 8B FP16, paged allocator so memory never biases the race)
 * and writes the best-throughput and best-TTFT-p95 settings into `staticBest.ts`.
 *
 * Run with:
 *   node --experimental-strip-types --import ./scripts/ts-hooks.mjs src/lessons/llm-serving/staticSearch.run.ts
 */
import { nodeFs } from '../../lib/nodeIo';
import {
  H100_80G,
  LLAMA3_8B,
  RTX_4090,
  evaluateKvMemoryMap,
  simulate,
  type ServingConfig,
} from './serve';
import {
  LAUNCH_BURST_TRACE,
  MEMORY_MAP_SEQUENCES,
  RACE_TRACE,
  TROLLEY_TRACE,
  summarizeTrace,
} from './trace';

export const STATIC_BATCH_SIZES = [2, 4, 6, 8, 12, 16] as const;
export const STATIC_WAIT_MS = [0, 25, 50, 100, 200, 400] as const;

export function runStaticRaceSearch() {
  const rows: {
    batchSize: number;
    maxWaitMs: number;
    throughputTokPerSec: number;
    ttftP50Ms: number;
    ttftP95Ms: number;
    tpotP50Ms: number;
    tpotP95Ms: number;
    idleSlotShare: number;
    totalTimeMs: number;
  }[] = [];

  for (const batchSize of STATIC_BATCH_SIZES) {
    for (const maxWaitMs of STATIC_WAIT_MS) {
      const cfg: ServingConfig = {
        batching: 'static',
        staticBatchSize: batchSize,
        staticMaxWaitMs: maxWaitMs,
        maxRunning: batchSize,
        tokenBudget: null,
        allocator: 'paged',
        blockSize: 16,
        prefixSharing: false,
        admission: 'fcfs',
        gpu: RTX_4090,
        model: LLAMA3_8B,
      };
      const res = simulate(RACE_TRACE, cfg);
      rows.push({
        batchSize,
        maxWaitMs,
        throughputTokPerSec: +res.metrics.throughputTokPerSec.toFixed(2),
        ttftP50Ms: +res.metrics.ttftP50Ms.toFixed(1),
        ttftP95Ms: +res.metrics.ttftP95Ms.toFixed(1),
        tpotP50Ms: +res.metrics.tpotP50Ms.toFixed(2),
        tpotP95Ms: +res.metrics.tpotP95Ms.toFixed(2),
        idleSlotShare: +res.metrics.idleSlotShare.toFixed(4),
        totalTimeMs: +res.metrics.totalTimeMs.toFixed(1),
      });
    }
  }

  const bestByThroughput = [...rows].sort((a, b) => b.throughputTokPerSec - a.throughputTokPerSec)[0];
  const bestByTtft = [...rows].sort((a, b) => a.ttftP95Ms - b.ttftP95Ms)[0];

  const contRes = simulate(RACE_TRACE, {
    batching: 'continuous',
    maxRunning: bestByThroughput.batchSize,
    tokenBudget: null,
    allocator: 'paged',
    blockSize: 16,
    prefixSharing: false,
    admission: 'fcfs',
    gpu: RTX_4090,
    model: LLAMA3_8B,
  });

  return {
    gridSize: rows.length,
    batchSizes: [...STATIC_BATCH_SIZES],
    waitMs: [...STATIC_WAIT_MS],
    bestByThroughput,
    bestByTtft,
    continuousAtSameSlots: {
      maxRunning: bestByThroughput.batchSize,
      throughputTokPerSec: +contRes.metrics.throughputTokPerSec.toFixed(2),
      ttftP50Ms: +contRes.metrics.ttftP50Ms.toFixed(1),
      ttftP95Ms: +contRes.metrics.ttftP95Ms.toFixed(1),
      tpotP50Ms: +contRes.metrics.tpotP50Ms.toFixed(2),
      tpotP95Ms: +contRes.metrics.tpotP95Ms.toFixed(2),
      idleSlotShare: +contRes.metrics.idleSlotShare.toFixed(4),
      totalTimeMs: +contRes.metrics.totalTimeMs.toFixed(1),
    },
  };
}

const procArgv = (globalThis as unknown as { process?: { argv?: string[] } }).process?.argv;
const isMain = Boolean(procArgv?.[1] && import.meta.url === `file://${procArgv[1]}`);
if (isMain) {
  const fs = await nodeFs();
  const out = runStaticRaceSearch();

  const src = `// authored-by: Gemini Antigravity
// Generated by staticSearch.run.ts: best static-batching settings on RACE_TRACE (36 configs).
export const STATIC_RACE_SEARCH = ${JSON.stringify(out, null, 2)} as const;
`;
  fs.writeFileSync(new URL('./staticBest.ts', import.meta.url), src);

  // Also print diagnostic numbers for Widgets A, B, C, D
  const launch = simulate(LAUNCH_BURST_TRACE, {
    batching: 'continuous',
    maxRunning: 1,
    tokenBudget: null,
    allocator: 'paged',
    blockSize: 16,
    prefixSharing: false,
    admission: 'fcfs',
    gpu: H100_80G,
    model: LLAMA3_8B,
  });
  const last200 = launch.requests[launch.requests.length - 1];
  console.log('LAUNCH_BURST (200 users, H100, B=1):');
  console.log('  summary:', summarizeTrace(LAUNCH_BURST_TRACE));
  console.log('  200th user TTFT:', (last200.ttftMs / 1000).toFixed(1), 's | p50 TTFT:', (launch.metrics.ttftP50Ms / 1000).toFixed(1), 's | total:', (launch.metrics.totalTimeMs / 1000).toFixed(1), 's');

  console.log('\nWIDGET B (RACE_TRACE, RTX 4090):');
  console.log('  summary:', summarizeTrace(RACE_TRACE));
  console.log('  best static (throughput):', out.bestByThroughput);
  console.log('  best static (ttft p95):', out.bestByTtft);
  console.log('  continuous (same slots):', out.continuousAtSameSlots);

  console.log('\nWIDGET C (TROLLEY_TRACE, RTX 4090, 16k doc):');
  console.log('  summary:', summarizeTrace(TROLLEY_TRACE));
  for (const budget of [null, 256, 512, 1024, 2048, 4096]) {
    const r = simulate(TROLLEY_TRACE, {
      batching: 'continuous',
      maxRunning: 16,
      tokenBudget: budget,
      allocator: 'paged',
      blockSize: 16,
      prefixSharing: false,
      admission: 'fcfs',
      gpu: RTX_4090,
      model: LLAMA3_8B,
    });
    const doc = r.requests.find((x) => x.kind === 'doc')!;
    console.log(
      `  budget=${String(budget ?? 'off').padStart(4)} | worstTPOT=${r.metrics.worstTpotMs.toFixed(1).padStart(6)} ms | docTTFT=${doc.ttftMs.toFixed(0).padStart(5)} ms | tok/s=${r.metrics.throughputTokPerSec.toFixed(1)}`,
    );
  }

  console.log('\nWIDGET D (MEMORY_MAP_SEQUENCES, RTX 4090, maxModelLen=8192):');
  for (const [mode, bs, ps] of [
    ['reserve-max', 16, false],
    ['reserve-grow', 16, false],
    ['paged', 8, false],
    ['paged', 16, false],
    ['paged', 32, false],
    ['paged', 16, true],
  ] as const) {
    const rep = evaluateKvMemoryMap({
      sequences: MEMORY_MAP_SEQUENCES,
      mode,
      blockSize: bs,
      prefixSharing: ps,
      maxModelLen: 8192,
      gpu: RTX_4090,
      model: LLAMA3_8B,
    });
    console.log(
      `  ${(mode + (mode === 'paged' ? ` b=${bs}` : '') + (ps ? ' +prefix' : '')).padEnd(26)} | fit=${String(rep.sequencesFit).padStart(2)}/64 | waste=${rep.wastePct.toFixed(1).padStart(4)}% | thr=${rep.decodeThroughputTokPerSec.toFixed(0).padStart(4)} tok/s | util=${rep.decodeComputeUtilPct.toFixed(1)}%`,
    );
  }
}
