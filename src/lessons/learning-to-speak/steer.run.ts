/** Runs searchSteer for each target with the recorded run's final weights; writes steerResults.ts. */
import { Gpt } from '../../lib/compute/gpt';
import { CPU_RUN } from '../../lib/compute/gptReference';
import { nodeFs } from '../../lib/nodeIo';
import { searchSteer, steer, STEER_PROMPT, TARGETS } from './steer';

const fs = await nodeFs();
const b = fs.readFileSync(new URL('../../lib/compute/tinyGpt.cpu.bin', import.meta.url));
const m = new Gpt(CPU_RUN.cfg);
m.load(new Float32Array(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)));
const greedy = steer(m, STEER_PROMPT, []);
console.log('greedy:', JSON.stringify(greedy));
const out = TARGETS.map((target) => {
  const t = Date.now();
  const r = searchSteer(m, STEER_PROMPT, target);
  console.log(JSON.stringify(target), r.cost, r.exact, r.plansTried, JSON.stringify(steer(m, STEER_PROMPT, r.plan)), `${((Date.now() - t) / 1000).toFixed(0)} s`);
  return { target, ...r };
});
fs.writeFileSync(new URL('./steerResults.ts', import.meta.url), `// authored-by: Claude Opus 5.5\n// Generated by steer.run.ts. Do not edit by hand.\nexport const STEER_GREEDY = ${JSON.stringify(greedy)};\nexport const STEER_RESULTS = ${JSON.stringify(out)} as const;\n`);
