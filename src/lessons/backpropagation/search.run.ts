/**
 * Exhaustive search over Brief 2 (48 settings x 5 seeds) and Brief 3 (32 settings)
 * of Lab: The Credit-Assignment Workbench.
 *
 * Run with:
 *   node --experimental-strip-types --import ./scripts/ts-hooks.mjs src/lessons/backpropagation/search.run.ts
 */
import { nodeFs } from '../../lib/nodeIo';
import {
  BRIEF2_ACTS,
  BRIEF2_INIT_MODES,
  BRIEF2_LRS,
  BRIEF3_LRS,
  evaluateBrief2,
  evaluateBrief3,
  type Brief2Config,
} from './creditLab';

interface Brief2Record {
  initMode: Brief2Config['initMode'];
  act: Brief2Config['act'];
  lr: number;
  solvedSeeds: number;
  meanLoss: number;
  meanAcc: number;
  meanSolveStep: number | null;
  pass: boolean;
}

interface Brief3Record {
  trainH1: boolean;
  trainH2: boolean;
  trainOut: boolean;
  lr: number;
  unfrozenHiddenCount: number;
  finalLoss: number;
  finalAcc: number;
  solvedStep: number | null;
  finalSeparable: boolean;
  pass: boolean;
}

const b2Rows: Brief2Record[] = [];
for (const initMode of BRIEF2_INIT_MODES) {
  for (const act of BRIEF2_ACTS) {
    for (const lr of BRIEF2_LRS) {
      const r = evaluateBrief2({ initMode, act, lr });
      b2Rows.push({
        initMode,
        act,
        lr,
        solvedSeeds: r.solvedSeeds,
        meanLoss: Number(r.meanLoss.toFixed(6)),
        meanAcc: Number(r.meanAcc.toFixed(4)),
        meanSolveStep: r.meanSolveStep !== null ? Number(r.meanSolveStep.toFixed(2)) : null,
        pass: r.pass,
      });
    }
  }
}

const b2Passing = b2Rows.filter((r) => r.pass);
b2Passing.sort((a, b) => (a.meanSolveStep ?? 999) - (b.meanSolveStep ?? 999));

const b3Rows: Brief3Record[] = [];
for (const trainH1 of [false, true]) {
  for (const trainH2 of [false, true]) {
    for (const trainOut of [false, true]) {
      for (const lr of BRIEF3_LRS) {
        const r = evaluateBrief3({ trainH1, trainH2, trainOut, lr });
        b3Rows.push({
          trainH1,
          trainH2,
          trainOut,
          lr,
          unfrozenHiddenCount: r.unfrozenHiddenCount,
          finalLoss: Number(r.finalLoss.toFixed(6)),
          finalAcc: Number(r.finalAcc.toFixed(4)),
          solvedStep: r.solvedStep,
          finalSeparable: r.finalSeparable,
          pass: r.pass,
        });
      }
    }
  }
}

const b3Passing = b3Rows.filter((r) => r.pass);
const b3MinUnfrozen = Math.min(...b3Passing.map((r) => r.unfrozenHiddenCount));
const b3Optimal = b3Passing
  .filter((r) => r.unfrozenHiddenCount === b3MinUnfrozen)
  .sort((a, b) => (a.solvedStep ?? 999) - (b.solvedStep ?? 999));

const out = `// authored-by: Gemini Antigravity
// Generated by src/lessons/backpropagation/search.run.ts — do not hand-edit.
import type { CreditAct, InitMode } from './creditLab';

export interface Brief2SearchRow {
  initMode: InitMode;
  act: CreditAct;
  lr: number;
  solvedSeeds: number;
  meanLoss: number;
  meanAcc: number;
  meanSolveStep: number | null;
  pass: boolean;
}

export interface Brief3SearchRow {
  trainH1: boolean;
  trainH2: boolean;
  trainOut: boolean;
  lr: number;
  unfrozenHiddenCount: number;
  finalLoss: number;
  finalAcc: number;
  solvedStep: number | null;
  finalSeparable: boolean;
  pass: boolean;
}

export const BRIEF2_GRID: readonly Brief2SearchRow[] = ${JSON.stringify(b2Rows, null, 2)};

export const BRIEF2_SUMMARY = {
  total: ${b2Rows.length},
  passing: ${b2Passing.length},
  brokenPassing: ${b2Rows.filter((r) => r.initMode === 'broken' && r.pass).length},
  zerosPassing: ${b2Rows.filter((r) => r.initMode === 'zeros' && r.pass).length},
  asymLargePassing: ${b2Rows.filter((r) => r.initMode === 'asym-large' && r.pass).length},
  asymSmallPassing: ${b2Rows.filter((r) => r.initMode === 'asym-small' && r.pass).length},
  fastest: ${JSON.stringify(b2Passing[0])},
} as const;

export const BRIEF3_GRID: readonly Brief3SearchRow[] = ${JSON.stringify(b3Rows, null, 2)};

export const BRIEF3_SUMMARY = {
  total: ${b3Rows.length},
  passing: ${b3Passing.length},
  outputOnlyPassing: ${b3Rows.filter((r) => !r.trainH1 && !r.trainH2 && r.trainOut && r.pass).length},
  outputFrozenPassing: ${b3Rows.filter((r) => !r.trainOut && r.pass).length},
  minUnfrozenHidden: ${b3MinUnfrozen},
  minUnfrozenPassing: ${b3Optimal.length},
  fastestMinUnfrozen: ${JSON.stringify(b3Optimal[0])},
  fastestOverall: ${JSON.stringify([...b3Passing].sort((a, b) => (a.solvedStep ?? 999) - (b.solvedStep ?? 999))[0])},
} as const;
`;

const { writeFileSync } = await nodeFs();
writeFileSync(new URL('./results.ts', import.meta.url), out);
console.log('Wrote src/lessons/backpropagation/results.ts');
console.log('Brief 2:', {
  total: b2Rows.length,
  passing: b2Passing.length,
  fastest: b2Passing[0],
});
console.log('Brief 3:', {
  total: b3Rows.length,
  passing: b3Passing.length,
  minUnfrozenHidden: b3MinUnfrozen,
  minUnfrozenPassing: b3Optimal.length,
  fastestMinUnfrozen: b3Optimal[0],
});
