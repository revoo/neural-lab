/**
 * Records the "learning to draw" reference run (CPU tier) into drawResults.ts:
 *   node --experimental-strip-types --import ./scripts/ts-hooks.mjs src/lessons/diffusion/draw.run.ts
 */
import { CpuMlpEngine } from '../../lib/compute/cpuBackend';
import { nodeFs } from '../../lib/nodeIo';
import { decodeDraw, DRAW_RUN, drawMlp, drawMoments, nearestTrain, realRange, sampleDraw, trainDraw } from './draw';

const fs = await nodeFs();
const d = decodeDraw(new Uint8Array(fs.readFileSync(new URL('./fashion8.bin', import.meta.url))));
const bar = realRange(d);
const eng = new CpuMlpEngine(drawMlp(DRAW_RUN));
const r2 = (v: number) => +v.toFixed(2);
const hist: { step: number; nn: number[]; samples: number[][] }[] = [];
let journey: number[][] = [];
const t0 = Date.now();
await trainDraw(eng, d, DRAW_RUN, async (step) => {
  const keep: number[][] = [];
  const xs = await sampleDraw(eng, 16, 7, step === DRAW_RUN.steps ? (t, x) => [99, 90, 75, 60, 45, 30, 20, 10, 5, 0].includes(t) && keep.push(Array.from(x, r2)) : undefined);
  if (keep.length) journey = keep;
  const nn = xs.map((x) => r2(nearestTrain(x, d.train)));
  hist.push({ step, nn, samples: xs.map((x) => Array.from(x, r2)) });
  console.log(`step ${step} ${((Date.now() - t0) / 1000).toFixed(0)} s: nearest-real median ${[...nn].sort((a, b) => a - b)[8]} min ${Math.min(...nn)} (bar ${bar.toFixed(2)})`);
});
const out = { bar: r2(bar), moments: drawMoments(hist, r2(bar)), checkpoints: hist, journey };
fs.writeFileSync(new URL('./drawResults.ts', import.meta.url), `// authored-by: Claude Opus 5.5\n// Generated by draw.run.ts. Do not edit by hand.\nexport const DRAW_RESULTS = ${JSON.stringify(out)} as const;\n`);
console.log(out.moments);
