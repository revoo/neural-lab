/**
 * The "Ship the tiny GPT" search: every design in `allDesigns()` on both seeds. Sharded:
 *   node --experimental-strip-types --import ./scripts/ts-hooks.mjs src/lessons/tiny-gpt/search.run.ts <shard> <shards>
 * writes scratch/ship-<shard>.json; then `search.run.ts merge <shards>` writes `results.ts`.
 */
import { runTraining } from '../../lib/compute/gptRun';
import { InlineCpuTrainer } from '../../lib/compute/gptTrainerCore';
import { prepareCorpus } from '../../lib/corpora/grimm';
import { argv, nodeFs } from '../../lib/nodeIo';
import { allDesigns, designKey, designParams, designSpec, designSteps, SEEDS } from './shipLab';

const fs = await nodeFs();
const [a, b] = argv();
type Row = { key: string; params: number; steps: number; val: number[]; curve: [number, number][][] };

if (a === 'merge') {
  const rows: Row[] = [];
  for (let s = 0; s < +b; s++) rows.push(...(JSON.parse(fs.readFileSync(`scratch/ship-${s}.json`, 'utf8')) as Row[]));
  rows.sort((x, y) => x.key.localeCompare(y.key));
  const body = rows.map((r) => `  ${JSON.stringify(r.key)}: ${JSON.stringify({ params: r.params, steps: r.steps, val: r.val.map((v) => +v.toFixed(4)), curve: r.curve.map((c) => c.map(([s, v]) => [s, +v.toFixed(3)])) })},`).join('\n');
  fs.writeFileSync(new URL('./results.ts', import.meta.url), `// authored-by: Claude Opus 5.5\n// Generated by search.run.ts merge: every design of the Ship-the-tiny-GPT grid on both seeds. Do not edit.\nexport type ShipResult = { params: number; steps: number; val: readonly number[]; curve: readonly (readonly (readonly [number, number])[])[] };\nexport const SHIP_RESULTS: Record<string, ShipResult> = {\n${body}\n};\n`);
  console.log(`merged ${rows.length} designs`);
} else {
  const shard = +a;
  const shards = +b;
  const corpus = prepareCorpus(fs.readFileSync(new URL('../../lib/corpora/grimm.txt', import.meta.url), 'utf8'));
  const mine = allDesigns().filter((_, i) => i % shards === shard);
  const rows: Row[] = [];
  for (const x of mine) {
    const val: number[] = [];
    const curve: [number, number][][] = [];
    for (const seed of SEEDS) {
      const c: [number, number][] = [];
      await runTraining(designSpec(x, seed), corpus, new InlineCpuTrainer(designSpec(x, seed).cfg), (cp) => void c.push([cp.step, cp.valLoss]));
      val.push(c.at(-1)![1]);
      curve.push(c);
    }
    rows.push({ key: designKey(x), params: designParams(x), steps: designSteps(x), val, curve });
    fs.writeFileSync(`scratch/ship-${shard}.json`, JSON.stringify(rows));
    console.log(designKey(x), designParams(x), designSteps(x), val.map((v) => v.toFixed(3)).join(' '));
  }
}
