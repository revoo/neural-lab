import { trainBpe } from '../../lib/corpora/bpe';
import { prepareCorpus, VOCAB } from '../../lib/corpora/grimm';
import { nodeFs } from '../../lib/nodeIo';

const fs = await nodeFs();
const c = prepareCorpus(fs.readFileSync(new URL('../../lib/corpora/grimm.txt', import.meta.url), 'utf8'));
const bpe = trainBpe(c.text.slice(0, c.split), 500, VOCAB);
fs.writeFileSync(
  new URL('./bpeMerges.ts', import.meta.url),
  `// authored-by: Claude Opus 5.5\n// Generated by bpe.run.ts: 500 BPE merges learned on the training tales. Do not edit.\nexport const MERGES: [string, string][] = ${JSON.stringify(bpe.merges)};\n`,
);
