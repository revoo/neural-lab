/**
 * Records the "learning to see" reference runs into seeResults.ts and the final weights into
 * seeNet.bin. The lesson's run (SEE_RUN, small first-layer start), plus seeds 1–3 of both
 * first-layer starts (small and He) for the fair comparison the lesson quotes.
 *   node --experimental-strip-types --import ./scripts/ts-hooks.mjs src/lessons/learning-to-see/see.run.ts
 */
import { nodeFs } from '../../lib/nodeIo';
import { decodeFashion } from './fashion';
import { CONFIG, EDGE_QUANTILE, measureSee, nearestCentroidAccuracy, randomFilterBar, SEE_RUN, seeMoments, trainSee, type SeeCheckpoint } from './see';

const fs = await nodeFs();
const data = decodeFashion(new Uint8Array(fs.readFileSync(new URL('./fashion.bin', import.meta.url))));
const edgeBar = randomFilterBar(CONFIG.k1, 20000, EDGE_QUANTILE);
const rawNC = nearestCentroidAccuracy(data.train.slice(0, 1000), data.trainY.slice(0, 1000), data.test, data.testY);
const r4 = (v: number) => +v.toFixed(4);

const hist: SeeCheckpoint[] = [];
let final: Float32Array = new Float32Array(0);
trainSee(SEE_RUN, data, (step, params, net) => {
  const m = measureSee(net, data);
  hist.push({ step, acc: m.acc, nc: r4(m.nc), edge: m.edge.map(r4), filters: m.filters.map((f) => f.map(r4)) });
  final = params;
  console.log(`step ${step} acc ${m.acc.toFixed(3)} nc ${m.nc.toFixed(3)} edges ${m.edge.filter((e) => e > edgeBar).length}`);
});
fs.writeFileSync(new URL('./seeNet.bin', import.meta.url), new Uint8Array(final.buffer));

const compare: { start: string; seed: number; acc: number; edges: number; firstEdge: number | null }[] = [];
for (const [start, firstStd] of [['small', 0.02], ['He', undefined]] as const)
  for (const seed of [1, 2, 3]) {
    const h: { step: number; nc: number; edge: number[]; acc: number }[] = [];
    trainSee({ ...SEE_RUN, cfg: { ...CONFIG, firstStd }, seed }, data, (step, _p, net) => {
      const m = measureSee(net, data);
      h.push({ step, nc: m.nc, edge: m.edge, acc: m.acc });
    });
    const last = h.at(-1)!;
    compare.push({ start, seed, acc: last.acc, edges: last.edge.filter((e) => e > edgeBar).length, firstEdge: seeMoments(h, edgeBar, rawNC).find((m) => m.id === 'first-edge')?.step ?? null });
    console.log(compare.at(-1));
  }

const out = { edgeBar: r4(edgeBar), rawNC, moments: seeMoments(hist, edgeBar, rawNC), checkpoints: hist, compare };
fs.writeFileSync(new URL('./seeResults.ts', import.meta.url), `// authored-by: Claude Opus 5.5\n// Generated by see.run.ts. Do not edit by hand.\nexport const SEE_RESULTS = ${JSON.stringify(out)} as const;\n`);
console.log(out.moments);
