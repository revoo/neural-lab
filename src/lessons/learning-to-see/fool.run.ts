/** Runs searchFool on the three brief photos with the shipped network; writes foolResults.ts. */
import { nodeFs } from '../../lib/nodeIo';
import { Cnn } from './cnn';
import { decodeFashion } from './fashion';
import { briefImages, searchFool } from './fool';
import { SEE_RUN } from './see';

const fs = await nodeFs();
const data = decodeFashion(new Uint8Array(fs.readFileSync(new URL('./fashion.bin', import.meta.url))));
const b = fs.readFileSync(new URL('./seeNet.bin', import.meta.url));
const net = new Cnn(SEE_RUN.cfg);
net.p.set(new Float32Array(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)));
const imgs = briefImages(net, data);
const out = imgs.map((i) => {
  const t = Date.now();
  const r = searchFool(net, data.test[i], data.testY[i]);
  console.log(i, data.testY[i], r.method, r.best.length, r.pairsChecked, `${((Date.now() - t) / 1000).toFixed(0)} s`);
  return { image: i, label: data.testY[i], ...r };
});
fs.writeFileSync(new URL('./foolResults.ts', import.meta.url), `// authored-by: Claude Opus 5.5\n// Generated by fool.run.ts. Do not edit by hand.\nexport const FOOL_RESULTS = ${JSON.stringify(out)} as const;\n`);
